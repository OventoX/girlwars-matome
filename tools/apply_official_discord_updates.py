def main():
    with open(DATA_JS_PATH, 'r', encoding='utf-8') as f:
        content = f.read()

    idx = content.find('window.GIRLWARS_DATA = ')
    header_part = content[:idx]
    json_str = content[idx + len('window.GIRLWARS_DATA = '):].rstrip(';\n ')
    data = json.loads(json_str)

    # Snapshot original records to verify only allowed IDs are modified
    orig_snapshot = {c['id']: json.dumps(c, ensure_ascii=False, sort_keys=True) for c in data}

    updated_ids = []
    story_added_count = 0

    for c in data:
        cid = c['id']
        if cid in SUCCEEDED_MAIN_FILES:
            main_file = SUCCEEDED_MAIN_FILES[cid]
            info_file = f"{cid}_info.webp"

            # Verify local files exist
            assert os.path.isfile(os.path.join(OFFICIAL_DIR, main_file)), f"Missing {main_file}"
            assert os.path.isfile(os.path.join(OFFICIAL_DIR, info_file)), f"Missing {info_file}"

            old_illust_url = c.get('illustUrl')
            new_main_rel = f"assets/official/{main_file}"
            new_info_rel = f"assets/official/{info_file}"

            c['illustUrl'] = new_main_rel
            c['illustSource'] = '少女ウォーズ公式Discord「UR図鑑」'
            c['illustCredit'] = '少女ウォーズ公式Discord「UR図鑑」 / 公式イラスト'

            imgs = c.setdefault('images', [])
            for img in imgs:
                if img.get('url') == old_illust_url:
                    img['url'] = new_main_rel
                    img['source'] = '少女ウォーズ公式Discord「UR図鑑」'
                    img['credit'] = '少女ウォーズ公式Discord「UR図鑑」 / 公式イラスト'

            if not any(i.get('label') == '公式性能紹介' for i in imgs):
                imgs.append({
                    'label': '公式性能紹介',
                    'url': new_info_rel,
                    'source': '少女ウォーズ公式Discord「UR図鑑」',
                    'credit': '少女ウォーズ公式Discord「UR図鑑」 / 公式性能紹介'
                })

            if not c.get('story') or not str(c.get('story')).strip():
                if cid in STORIES:
                    c['story'] = STORIES[cid]
                    story_added_count += 1

            updated_ids.append(cid)

        elif cid == 'wiki_53':
            # 作業3: 立花誾千代（花嫁）のリンク切れ修正（images[0].url を使用）
            if c.get('images') and len(c['images']) > 0:
                c['illustUrl'] = c['images'][0]['url']

    # Verify non-target records have zero diff
    changed_ids = []
    for c in data:
        cid = c['id']
        if json.dumps(c, ensure_ascii=False, sort_keys=True) != orig_snapshot[cid]:
            changed_ids.append(cid)

    unexpected = set(changed_ids) - set(SUCCEEDED_MAIN_FILES.keys()) - {'wiki_53'}
    assert not unexpected, f"Unexpected records modified: {unexpected}"

    total_images = sum(len(c.get('images', [])) for c in data)
    with_variants = sum(1 for c in data if len(c.get('images', [])) > 1)

    print(f"Updated official records: {len(updated_ids)}")
    print(f"Story added to empty records: {story_added_count}")
    print(f"Total changed records in data.js: {len(changed_ids)} (unexpected: {len(unexpected)})")
    print(f"Total images: {total_images}, With variants (>1): {with_variants}")

    new_header = re.sub(r'withVariantsCount:\s*\d+', f'withVariantsCount: {with_variants}', header_part)
    new_header = re.sub(r'totalImagesCount:\s*\d+', f'totalImagesCount: {total_images}', new_header)

    new_content = f"{new_header}window.GIRLWARS_DATA = {json.dumps(data, ensure_ascii=False, indent=2)};\n"
    with open(DATA_JS_PATH, 'w', encoding='utf-8') as f:
        f.write(new_content)
    print(f"[SAVED] {DATA_JS_PATH}")

if __name__ == '__main__':
    main()
